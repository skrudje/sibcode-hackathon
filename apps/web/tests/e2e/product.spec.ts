import { test, expect } from '@playwright/test'
import { readFile, mkdir } from 'node:fs/promises'

test('полный путь: три источника → профиль → рекомендация → CSV → новая покупка', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('Пароль', { exact: true }).fill(process.env.DEMO_PASSWORD || 'HryukersDemo2026!')
  await page.getByRole('button', { name: 'Войти в платформу' }).click()
  await expect(page.getByRole('heading', { name: 'Обзор платформы' })).toBeVisible()
  const initial = await (await page.request.get('/api/v1/summary')).json()
  expect(initial.customer_count, 'E2E uses a fresh, separate hryukers-e2e Compose project').toBe(0)
  await page.getByRole('button', { name: 'Запустить демосценарий' }).click()
  await expect.poll(async () => (await (await page.request.get('/api/v1/summary')).json()).event_count, { timeout: 90_000 }).toBe(18)
  await expect(page.getByRole('button', { name: 'Повторить демозагрузку' })).toBeEnabled()
  await mkdir('../../.data/qa', { recursive: true })
  await page.screenshot({ path: '../../.data/qa/overview.png', fullPage: true })
  await page.getByRole('link', { name: 'Клиенты', exact: true }).click()
  await page.getByRole('textbox', { name: 'Поиск клиентов' }).fill('G001')
  await page.getByRole('link', { name: 'Открыть G001', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Посетитель 001' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Книжный C', exact: true })).toBeVisible()
  await page.screenshot({ path: '../../.data/qa/profile.png', fullPage: true })
  await page.getByRole('link', { name: 'Сегменты', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Клиенты сегмента' })).toBeVisible()
  const segments = await (await page.request.get('/api/v1/segments')).json()
  const members = await (await page.request.get(`/api/v1/segments/${segments.items[0].id}/members`)).json()
  expect(members.evaluation).toMatchObject({ eligible_count: 5, ineligible_count: 3, unknown_count: 2 })
  await page.getByRole('link', { name: 'Кампании', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Сформировать CSV' })).toBeEnabled()
  await page.getByRole('button', { name: 'Сформировать CSV' }).click()
  await expect(page.getByText('Выгрузка сформирована.', { exact: false })).toBeVisible()
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Скачать CSV' }).first().click()
  const download = await downloadEvent
  const content = await readFile((await download.path())!, 'utf8')
  expect(content).toContain('g001@example.invalid')
  expect(content).not.toContain('g005-a@example.invalid')
  await expect(page.getByRole('button', { name: 'Сформировать CSV' })).toBeDisabled()
  await page.getByRole('link', { name: 'Источники данных', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить покупку в C' }).click()
  await expect.poll(async () => (await (await page.request.get('/api/v1/summary')).json()).event_count).toBe(19)
  await page.getByRole('link', { name: 'Клиенты', exact: true }).click()
  await page.getByRole('textbox', { name: 'Поиск клиентов' }).fill('G001')
  await page.getByRole('link', { name: 'Открыть G001', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Подходящего предложения пока нет' })).toBeVisible()
  await page.screenshot({ path: '../../.data/qa/profile-after.png', fullPage: true })
  expect(errors).toEqual([])
})

test('формы правил и мобильная вёрстка', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Пароль', { exact: true }).fill(process.env.DEMO_PASSWORD || 'HryukersDemo2026!')
  await page.getByRole('button', { name: 'Войти в платформу' }).click()
  await page.getByRole('link', { name: 'Сегменты', exact: true }).click()
  await page.getByRole('button', { name: 'Создать сегмент' }).click()
  await page.getByLabel('Название сегмента').fill('Тестовый сегмент')
  await page.getByRole('button', { name: 'Сохранить сегмент' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('link', { name: 'Рекомендации', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить правило' }).click()
  await page.getByLabel('Название правила').fill('Тестовое правило')
  await page.getByRole('combobox', { name: 'Сегмент', exact: true }).selectOption({ label: 'Тестовый сегмент' })
  await page.getByLabel('Заголовок предложения').fill('Новое предложение')
  await page.getByRole('button', { name: 'Сохранить правило' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Тестовое правило', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Кампании', exact: true }).click()
  await page.getByRole('button', { name: 'Создать кампанию' }).click()
  await page.getByLabel('Название', { exact: true }).fill('Тестовая SMS-кампания')
  await page.getByRole('combobox', { name: 'Правило рекомендации', exact: true }).selectOption({ label: 'Тестовое правило' })
  await page.getByRole('combobox', { name: 'Канал выгрузки' }).selectOption('sms')
  await page.getByRole('button', { name: 'Создать кампанию', exact: true }).last().click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Тестовая SMS-кампания' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('link', { name: 'Обзор', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Обзор платформы' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../../.data/qa/mobile.png', fullPage: true })
})
