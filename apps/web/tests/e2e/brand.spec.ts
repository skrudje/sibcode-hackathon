import { test, expect } from '@playwright/test'

test('представитель бренда выбирает колонки, загружает таблицу и видит только свой магазин', async ({ page }) => {
  const stamp = Date.now()
  const tenantName = `Бренд «Маяк ${stamp}»`
  const brandEmail = `brand-${stamp}@example.invalid`
  const brandPassword = 'BrandPassword2026!'
  const contactEmail = `visitor-${stamp}@example.invalid`
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('Email', { exact: true }).fill('admin@example.com')
  await page.getByLabel('Пароль', { exact: true }).fill(process.env.ADMIN_PASSWORD || 'HryukersAdmin2026!')
  await page.getByRole('button', { name: 'Войти в платформу' }).click()
  await page.getByRole('link', { name: 'Интеграции', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить арендатора', exact: true }).click()
  await page.getByLabel('Название', { exact: true }).fill(tenantName)
  await page.getByLabel('Категория', { exact: true }).fill('Книги')
  await page.getByRole('dialog').getByRole('button', { name: 'Добавить арендатора', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: 'Сотрудники', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(brandEmail)
  await page.getByLabel('Первый пароль · от 12 символов').fill(brandPassword)
  await page.getByLabel('Роль', { exact: true }).selectOption('brand')
  await page.getByLabel('Магазин представителя').selectOption({ label: tenantName })
  await page.getByRole('button', { name: 'Создать доступ', exact: true }).click()
  await expect(page.locator('.team-member').filter({ hasText: brandEmail })).toBeVisible()
  await page.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()

  await page.getByLabel('Email', { exact: true }).fill(brandEmail)
  await page.getByLabel('Пароль', { exact: true }).fill(brandPassword)
  await page.getByRole('button', { name: 'Войти в платформу' }).click()
  await expect(page.getByRole('heading', { name: tenantName, exact: true })).toBeVisible()
  await expect(page.getByText('Кабинет бренда', { exact: true })).toBeVisible()
  expect((await page.request.get('/api/v1/customers')).status()).toBe(403)
  const timestamp = new Date(Date.now() - 3600000).toISOString()
  const content = `ФИО;Номер;Эл. почта;Когда;Сумма\nНе передавать;+79132223344;${contactEmail.toUpperCase()};${timestamp};99999\nОшибка;wrong;bad;нет даты;99999\n`
  await page.getByLabel('Таблица бренда').setInputFiles({ name: 'crm.csv', mimeType: 'text/csv', buffer: Buffer.from(content) })
  await page.getByLabel('Колонка: Телефон').selectOption('1')
  await page.getByLabel('Колонка: Email').selectOption('2')
  await page.getByLabel('Колонка: Время взаимодействия').selectOption('3')
  await page.getByRole('button', { name: 'Проверить выбранные данные', exact: true }).click()
  await expect(page.getByRole('heading', { name: '3. Проверьте и передайте данные' })).toBeVisible()
  await expect(page.locator('.brand-preview-counts')).toContainText('1 корректных записей')
  await expect(page.locator('.brand-preview-counts')).toContainText('1 с ошибками')
  await page.screenshot({ path: '../../.data/qa/brand-portal.png', fullPage: true })
  await page.getByRole('button', { name: 'Передать 2 записей', exact: true }).click()
  const history = page.locator('section').filter({ has: page.getByRole('heading', { name: 'История загрузок вашего магазина' }) })
  await expect(history).toContainText('Есть замечания', { timeout: 90000 })
  await history.getByRole('button', { name: '1 · причины', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Причины отклонения записей' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../../.data/qa/brand-portal-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByLabel('Email', { exact: true }).fill('marketer@example.com')
  await page.getByLabel('Пароль', { exact: true }).fill(process.env.DEMO_PASSWORD || 'HryukersDemo2026!')
  await page.getByRole('button', { name: 'Войти в платформу' }).click()
  await page.getByRole('link', { name: 'Клиенты', exact: true }).click()
  await page.getByRole('textbox', { name: 'Поиск клиентов' }).fill(contactEmail)
  await expect(page.locator('.customer-browser tbody tr')).toHaveCount(1)
  await page.locator('.customer-browser tbody tr a.person').first().click()
  await expect(page.getByText(contactEmail, { exact: true }).first()).toBeVisible()
  expect(errors).toEqual([])
})
