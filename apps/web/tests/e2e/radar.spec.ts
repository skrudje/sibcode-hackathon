import { test, expect } from '@playwright/test'
import { readFile, mkdir } from 'node:fs/promises'

test('радар: реальные импорты → связь и события → кампания → CSV → новая покупка', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('Пароль', { exact: true }).fill(process.env.DEMO_PASSWORD || 'HryukersDemo2026!')
  await page.getByRole('button', { name: 'Войти в платформу' }).click()
  await page.getByRole('link', { name: 'Радар новых визитов', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Радар новых визитов', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Загрузить пример радара', exact: true }).click()
  await expect(page.getByText('Пример загружен через JSON, XLSX и CSV.', { exact: false })).toBeVisible({ timeout: 90_000 })
  const report = await (await page.request.get('/api/v1/radar')).json()
  const opportunity = report.opportunities.find((item: { origins: unknown[] }) => item.origins.length === 2)
  expect(opportunity.candidate_count).toBeGreaterThanOrEqual(15)
  const caption = `${opportunity.origins.map((n: { name: string }) => n.name).join(' + ')} → ${opportunity.destination.name}`
  await page.getByRole('button', { name: caption, exact: true }).click()
  await expect(page.getByRole('button', { name: 'Создать кампанию из возможности', exact: true })).toBeInViewport()
  await expect(page.getByText('Демо · Посетитель R026', { exact: true })).toBeVisible()
  await page.getByText('Демо · Посетитель R026', { exact: true }).click()
  await expect(page.getByRole('link', { name: 'Открыть профиль', exact: true })).toBeVisible()
  await page.getByText('Как получен результат', { exact: true }).click()
  await expect(page.getByText('Единица расчёта — уникальный клиент.', { exact: false })).toBeVisible()
  await mkdir('../../.data/qa', { recursive: true })
  await page.screenshot({ path: '../../.data/qa/radar.png' })
  await page.getByRole('button', { name: 'Создать кампанию из возможности', exact: true }).click()
  await page.getByLabel('Название кампании', { exact: true }).fill('Радар · E2E книжный')
  await page.getByRole('button', { name: 'Создать и проверить контакты', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Радар · E2E книжный', exact: true })).toBeVisible()
  const campaignId = new URL(page.url()).searchParams.get('campaign')
  expect(campaignId).toBeTruthy()
  const preview = await (await page.request.get(`/api/v1/campaigns/${campaignId}/preview`)).json()
  expect(preview.base_count).toBe(opportunity.candidate_count)
  expect(preview.eligible_count).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Сформировать CSV', exact: true }).click()
  await expect(page.getByText('Выгрузка сформирована.', { exact: false })).toBeVisible()
  const downloading = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Скачать CSV', exact: true }).first().click()
  const download = await downloading
  expect(await readFile((await download.path())!, 'utf8')).toContain('radar-r026@example.invalid')

  await page.getByRole('link', { name: 'Радар новых визитов', exact: true }).click()
  await page.getByRole('button', { name: caption, exact: true }).click()
  await page.getByRole('button', { name: 'Добавить покупку R026', exact: true }).click()
  await expect(page.getByText('Покупка R026 загружена.', { exact: false })).toBeVisible()
  await expect.poll(async () => (await (await page.request.get(`/api/v1/radar/opportunities/${opportunity.id}`)).json()).total).toBe(opportunity.candidate_count - 1)
  await expect(page.getByText('Демо · Посетитель R026', { exact: true })).not.toBeVisible()
  await page.getByRole('combobox', { name: 'Окно истории', exact: true }).selectOption('180')
  await expect(page.getByRole('heading', { name: 'Пока нет подтверждённых возможностей', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Окно истории', exact: true }).selectOption('90')
  await expect(page.getByRole('button', { name: caption, exact: true })).toBeVisible()
  await page.setViewportSize({ width: 900, height: 640 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
