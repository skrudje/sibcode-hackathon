import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('радар взаимодействий: объяснение → кампания → CSV → обновление аудитории', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('Пароль', { exact: true }).fill(process.env.DEMO_PASSWORD || 'HryukersDemo2026!')
  await page.getByRole('button', { name: 'Войти в платформу' }).click()
  await expect.poll(async () => (await (await page.request.get('/api/v1/summary')).json()).customer_count, { timeout: 90_000 }).toBeGreaterThan(500)
  await page.getByRole('link', { name: 'Радар новых визитов', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Радар новых визитов', exact: true })).toBeVisible()
  await expect.poll(async () => (await (await page.request.get('/api/v1/radar')).json()).total_opportunity_count, { timeout: 90_000 }).toBeGreaterThan(0)
  const report = await (await page.request.get('/api/v1/radar')).json()
  const opportunity = report.opportunities.find((item: { origins: unknown[]; offers: unknown[] }) => item.origins.length === 2 && item.offers.length)
  expect(opportunity).toBeTruthy()
  const caption = `${opportunity.origins.map((n: { name: string }) => n.name).join(' + ')} → ${opportunity.destination.name}`
  await page.getByRole('button', { name: caption, exact: true }).click()
  await expect(page.getByRole('button', { name: 'Создать кампанию из возможности', exact: true })).toBeInViewport()
  await page.getByRole('button', { name: 'Что значит «Отношение частот»', exact: true }).hover()
  await expect(page.getByRole('tooltip')).toContainText('Это наблюдение')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).not.toBeVisible()
  const audience = await (await page.request.get(`/api/v1/radar/opportunities/${opportunity.id}`)).json()
  const candidate = audience.items[0]
  await page.getByText(candidate.display_name, { exact: true }).click()
  await expect(page.getByRole('link', { name: 'Открыть профиль', exact: true })).toBeVisible()
  await page.getByText('Как получен результат', { exact: true }).click()
  await expect(page.getByText('Единица расчёта — уникальный клиент.', { exact: false })).toBeVisible()
  await page.screenshot({ path: '../../.data/qa/radar.png' })
  await page.getByRole('button', { name: 'Создать кампанию из возможности', exact: true }).click()
  await page.getByLabel('Название кампании', { exact: true }).fill('Новые знакомства · Проверка')
  await page.getByRole('button', { name: 'Создать и проверить контакты', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Новые знакомства · Проверка', exact: true })).toBeVisible()
  const campaignId = new URL(page.url()).searchParams.get('campaign')
  const preview = await (await page.request.get(`/api/v1/campaigns/${campaignId}/preview`)).json()
  expect(preview.base_count).toBe(opportunity.candidate_count)
  expect(preview.eligible_count).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Сформировать CSV', exact: true }).click()
  await expect(page.getByText('Выгрузка сформирована.', { exact: false })).toBeVisible()
  const downloading = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Скачать CSV', exact: true }).first().click()
  const download = await downloading
  expect(await readFile((await download.path())!, 'utf8')).toContain('@example.invalid')
  const profile = await (await page.request.get(`/api/v1/customers/${candidate.id}`)).json()
  const email = profile.contacts.find((contact: { channel: string }) => contact.channel === 'email').value
  await page.getByRole('link', { name: 'Источники данных', exact: true }).click()
  const timestamp = new Date(new Date(opportunity.as_of).getTime()-60_000).toISOString()
  await page.getByLabel(`Файл ${opportunity.destination.name}`, { exact: true }).setInputFiles({ name: 'contacts.csv', mimeType: 'text/csv', buffer: Buffer.from(`phone,email,time\n,${email},${timestamp}\n`) })
  await expect(page.getByText('Файл обработан.', { exact: false })).toBeVisible({ timeout: 90_000 })
  const campaign = await (await page.request.get(`/api/v1/campaigns/${campaignId}`)).json()
  await expect.poll(async () => (await (await page.request.get(`/api/v1/segments/${campaign.segment_id}/members`)).json()).total).toBe(opportunity.candidate_count-1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
